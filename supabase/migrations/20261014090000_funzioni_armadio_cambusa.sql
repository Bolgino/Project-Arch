-- ---------- Uso dalla dispensa (pubblico, controllato) ----------
-- p_righe: [{"id":"<uuid>", "qty": 1.5}, ...]
create or replace function public.usa_cambusa(p_utente text, p_righe jsonb)
returns jsonb
language plpgsql security definer
set search_path = public
as $$
declare
  v_utente text := coalesce(nullif(left(btrim(coalesce(p_utente, '')), 60), ''), 'Utente');
  v_mancanti text;
  v_voci jsonb;
  v_avvisi jsonb;
begin
  if p_righe is null or jsonb_typeof(p_righe) <> 'array' or jsonb_array_length(p_righe) = 0 then
    raise exception 'La lista è vuota';
  end if;
  if jsonb_array_length(p_righe) > 100 then raise exception 'Troppe righe'; end if;
  if exists (
    select 1 from jsonb_array_elements(p_righe) e
    where coalesce(e->>'id', '') !~ '^[0-9a-fA-F-]{36}$'
       or coalesce(e->>'qty', '') !~ '^[0-9]{1,6}(\.[0-9]{1,3})?$'
       or (e->>'qty')::numeric <= 0
  ) then
    raise exception 'Quantità non valide';
  end if;

  perform 1 from cambusa
  where id in (select (e->>'id')::uuid from jsonb_array_elements(p_righe) e)
  order by id for update;

  if exists (
    select 1 from jsonb_array_elements(p_righe) e
    left join cambusa c on c.id = (e->>'id')::uuid
    where c.id is null or c.stato = 'pending'
  ) then
    raise exception 'Uno dei prodotti non è disponibile: ricarica la pagina';
  end if;

  with n as (
    select (e->>'id')::uuid id, sum((e->>'qty')::numeric) qty from jsonb_array_elements(p_righe) e group by 1
  )
  select string_agg(format('%s (ce ne sono %s %s)', c.nome, coalesce(c.quantita, 0), coalesce(c.unita, '')), '; ')
    into v_mancanti
  from n join cambusa c on c.id = n.id
  where coalesce(c.quantita, 0) < n.qty;
  if v_mancanti is not null then
    raise exception 'Non ce n''è abbastanza: %', v_mancanti;
  end if;

  with n as (
    select (e->>'id')::uuid id, sum((e->>'qty')::numeric) qty from jsonb_array_elements(p_righe) e group by 1
  ), upd as (
    update cambusa c set quantita = c.quantita - n.qty
      from n where c.id = n.id
    returning c.nome, n.qty, c.unita, c.quantita rimasti, coalesce(c.soglia, 0) soglia
  ), ins as (
    insert into movimenti_cambusa (prodotto, quantita, unita, azione, utente)
    select nome, -qty, unita, 'consumo', v_utente from upd
    returning 1
  )
  select jsonb_agg(jsonb_build_object('nome', nome, 'qty', qty, 'unita', unita, 'rimasti', rimasti) order by nome),
         coalesce(jsonb_agg(jsonb_build_object('nome', nome, 'rimasti', rimasti, 'unita', unita) order by nome)
                  filter (where rimasti <= soglia), '[]'::jsonb)
    into v_voci, v_avvisi
  from upd;

  return jsonb_build_object('voci', v_voci, 'avvisi', v_avvisi);
end;
$$;

-- ---------- Rifornimento della dispensa (pubblico, controllato) ----------
-- p_righe: [{"id":"<uuid>", "qty": 2, "scadenza": "2026-12-31"}, ...]   (qty o scadenza possono mancare)
create or replace function public.rifornisci_cambusa(p_utente text, p_righe jsonb)
returns jsonb
language plpgsql security definer
set search_path = public
as $$
declare
  v_utente text := coalesce(nullif(left(btrim(coalesce(p_utente, '')), 60), ''), 'Utente');
  v_n int;
begin
  if p_righe is null or jsonb_typeof(p_righe) <> 'array' or jsonb_array_length(p_righe) = 0 then
    raise exception 'Nessuna modifica';
  end if;
  if jsonb_array_length(p_righe) > 200 then raise exception 'Troppe righe'; end if;
  if exists (
    select 1 from jsonb_array_elements(p_righe) e
    where coalesce(e->>'id', '') !~ '^[0-9a-fA-F-]{36}$'
       or (e ? 'qty' and e->>'qty' is not null and (e->>'qty' !~ '^[0-9]{1,6}(\.[0-9]{1,3})?$'))
       or (e ? 'scadenza' and e->>'scadenza' is not null and e->>'scadenza' !~ '^\d{4}-\d{2}-\d{2}$')
  ) then
    raise exception 'Dati non validi';
  end if;

  with n as (
    select (e->>'id')::uuid id,
           coalesce(nullif(e->>'qty', '')::numeric, 0) qty,
           nullif(e->>'scadenza', '')::date scad
    from jsonb_array_elements(p_righe) e
  ), upd as (
    update cambusa c
       set quantita = coalesce(c.quantita, 0) + n.qty,
           scadenza = coalesce(n.scad, c.scadenza)
      from n
     where c.id = n.id and (n.qty > 0 or n.scad is not null)
    returning c.nome, n.qty, c.unita
  ), ins as (
    insert into movimenti_cambusa (prodotto, quantita, unita, azione, utente)
    select nome, qty, unita, 'rifornimento', v_utente from upd where qty > 0
    returning 1
  )
  select count(*) into v_n from upd;

  return jsonb_build_object('aggiornati', v_n);
end;
$$;

-- ---------- Tempo reale: disponibilità dell'armadio aggiornata dal vivo ----------
do $$ begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'oggetti') then
      alter publication supabase_realtime add table public.oggetti;
