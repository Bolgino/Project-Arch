-- ---------- Prelievo dallo zaino (pubblico, controllato) ----------
-- p_righe: [{"tipo":"item"|"kit", "id":"<uuid>", "qty": 2}, ...]
create or replace function public.preleva_armadio(p_utente text, p_righe jsonb)
returns jsonb
language plpgsql security definer
set search_path = public
as $$
declare
  v_utente text := left(btrim(coalesce(p_utente, '')), 60);
  v_need jsonb;
  v_mancanti text;
  v_voci jsonb;
  v_avvisi jsonb;
  v_righe jsonb;
  v_dettagli text;
  v_id bigint;
begin
  if v_utente = '' then
    raise exception 'Scrivi chi sta prelevando';
  end if;
  if p_righe is null or jsonb_typeof(p_righe) <> 'array' or jsonb_array_length(p_righe) = 0 then
    raise exception 'Lo zaino è vuoto';
  end if;
  if jsonb_array_length(p_righe) > 100 then
    raise exception 'Troppe righe nello zaino';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_righe) e
    where coalesce(e->>'tipo', '') not in ('item', 'kit')
       or coalesce(e->>'id', '') !~ '^[0-9a-fA-F-]{36}$'
       or coalesce(e->>'qty', '') !~ '^[0-9]{1,4}$'
       or (e->>'qty')::int not between 1 and 500
  ) then
    raise exception 'Zaino non valido';
  end if;

  -- Righe con nome (e controllo che esistano)
  select jsonb_agg(jsonb_build_object(
           'tipo', r.tipo, 'id', r.id, 'qty', r.qty,
           'nome', coalesce(o.nome, p.nome)) order by r.ord)
    into v_righe
  from (
    select e->>'tipo' tipo, (e->>'id')::uuid id, (e->>'qty')::int qty, ord
    from jsonb_array_elements(p_righe) with ordinality as t(e, ord)
  ) r
  left join oggetti o on r.tipo = 'item' and o.id = r.id
  left join pacchetti p on r.tipo = 'kit' and p.id = r.id;

  if exists (select 1 from jsonb_array_elements(v_righe) e where e->>'nome' is null) then
    raise exception 'Qualcosa nello zaino non esiste più: ricarica la pagina';
  end if;
  if exists (
    select 1 from jsonb_array_elements(v_righe) e
    where e->>'tipo' = 'kit'
      and not exists (select 1 from componenti_pacchetto c where c.pacchetto_id = (e->>'id')::uuid)
  ) then
    raise exception 'Uno dei kit è vuoto';
  end if;

  -- Pezzi necessari per oggetto (kit espansi nei loro componenti)
  select coalesce(jsonb_object_agg(oggetto_id, qty), '{}'::jsonb) into v_need
  from (
    select oggetto_id, sum(qty)::int qty from (
      select (e->>'id')::uuid oggetto_id, (e->>'qty')::int qty
      from jsonb_array_elements(v_righe) e where e->>'tipo' = 'item'
      union all
      select c.oggetto_id, (e->>'qty')::int * coalesce(c.quantita_necessaria, 1)
      from jsonb_array_elements(v_righe) e
      join componenti_pacchetto c on c.pacchetto_id = (e->>'id')::uuid
      where e->>'tipo' = 'kit'
    ) x group by oggetto_id
  ) y;

  -- Blocca le righe per evitare prelievi contemporanei sullo stesso pezzo
  perform 1 from oggetti
  where id in (select key::uuid from jsonb_each_text(v_need))
  order by id for update;

  select string_agg(format('%s (ne servono %s, ce ne sono %s)', o.nome, n.value, coalesce(o.quantita_disponibile, 0)), '; ' order by o.nome)
    into v_mancanti
  from jsonb_each_text(v_need) n
  join oggetti o on o.id = n.key::uuid
  where coalesce(o.quantita_disponibile, 0) < n.value::int;

  if v_mancanti is not null then
    raise exception 'Non ce n''è abbastanza: %', v_mancanti;
  end if;

  with upd as (
    update oggetti o
       set quantita_disponibile = o.quantita_disponibile - n.value::int
      from jsonb_each_text(v_need) n
     where o.id = n.key::uuid
    returning o.id, o.nome, n.value::int qty, o.quantita_disponibile rimasti, coalesce(o.soglia_minima, 0) soglia
  )
  select jsonb_agg(jsonb_build_object('oggetto_id', id, 'nome', nome, 'qty', qty) order by nome),
         coalesce(jsonb_agg(jsonb_build_object('nome', nome, 'rimasti', rimasti, 'soglia', soglia) order by nome)
                  filter (where rimasti <= soglia), '[]'::jsonb)
    into v_voci, v_avvisi
  from upd;

  select string_agg(case when e->>'tipo' = 'kit' then 'KIT ' else '' end || (e->>'nome') || ' x' || (e->>'qty'), ', ')
    into v_dettagli
  from jsonb_array_elements(v_righe) e;

  insert into movimenti_armadio (utente, dettagli, tipo, voci, righe)
  values (v_utente, v_dettagli, 'prelievo', v_voci, v_righe)
  returning id into v_id;

  return jsonb_build_object('id', v_id, 'dettagli', v_dettagli, 'voci', v_voci, 'righe', v_righe, 'avvisi', v_avvisi);
end;
$$;

-- ---------- Carico (rifornimento o ordine arrivato), solo admin ----------
-- p_voci: [{"oggetto_id":"<uuid>", "qty": 5}, ...]
create or replace function public.carica_armadio(p_voci jsonb, p_nota text default null, p_ordine_id bigint default null)
returns jsonb
language plpgsql security definer
set search_path = public
as $$
declare
  v_voci jsonb;
  v_id bigint;
  v_nome text;
begin
  if not public.is_admin() then
    raise exception 'Solo l''admin può caricare materiale';
  end if;
  if p_voci is null or jsonb_typeof(p_voci) <> 'array' or jsonb_array_length(p_voci) = 0 then
    raise exception 'Niente da caricare';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_voci) e
    where coalesce(e->>'qty', '') !~ '^[0-9]{1,5}$' or (e->>'qty')::int < 1
       or coalesce(e->>'oggetto_id', '') !~ '^[0-9a-fA-F-]{36}$'
  ) then
    raise exception 'Quantità non valide';
  end if;

  with n as (
    select (e->>'oggetto_id')::uuid oggetto_id, sum((e->>'qty')::int)::int qty
    from jsonb_array_elements(p_voci) e group by 1
  ), upd as (
    update oggetti o
       set quantita_disponibile = coalesce(o.quantita_disponibile, 0) + n.qty
      from n
     where o.id = n.oggetto_id
    returning o.id, o.nome, n.qty
  )
  select jsonb_agg(jsonb_build_object('oggetto_id', id, 'nome', nome, 'qty', qty) order by nome)
    into v_voci from upd;

  if v_voci is null then
    raise exception 'Nessun oggetto trovato';
  end if;

  select coalesce(nullif(nome, ''), 'Admin') into v_nome from profili where id = auth.uid();

  insert into movimenti_armadio (utente, dettagli, tipo, voci, ordine_id)
  values (
    coalesce(v_nome, 'Admin'),
    coalesce(nullif(btrim(p_nota), ''), case when p_ordine_id is not null then 'Ordine arrivato' else 'Rifornimento' end)
      || ': ' || (select string_agg((e->>'nome') || ' x' || (e->>'qty'), ', ') from jsonb_array_elements(v_voci) e),
    'carico', v_voci, p_ordine_id)
  returning id into v_id;

  if p_ordine_id is not null then
    update ordini_forniture set stato = 'arrivato', arrivato_il = now() where id = p_ordine_id;
  end if;

  -- Le richieste "Serve!" per gli oggetti appena arrivati sono soddisfatte
  update richieste set completato = true
   where completato = false
     and oggetto_id in (select (e->>'oggetto_id')::uuid from jsonb_array_elements(v_voci) e);

  return jsonb_build_object('id', v_id, 'voci', v_voci);
end;
$$;

-- ---------- Annulla un prelievo o un carico, solo admin ----------
create or replace function public.annulla_movimento_armadio(p_id bigint)
returns jsonb
language plpgsql security definer
set search_path = public
as $$
declare
  m movimenti_armadio%rowtype;
  v_segno int;
  v_mancanti text;
begin
  if not public.is_admin() then
    raise exception 'Solo l''admin può annullare un movimento';
  end if;

  select * into m from movimenti_armadio where id = p_id for update;
  if not found then raise exception 'Movimento non trovato'; end if;
  if m.annullato_il is not null then raise exception 'Movimento già annullato'; end if;
  if m.voci is null or m.tipo not in ('prelievo', 'carico') or (m.tipo = 'prelievo' and m.righe is null) then
    raise exception 'Questo movimento è vecchio e non si può annullare in automatico';
  end if;

  v_segno := case when m.tipo = 'prelievo' then 1 else -1 end;

  perform 1 from oggetti
  where id in (select (e->>'oggetto_id')::uuid from jsonb_array_elements(m.voci) e)
  order by id for update;

  if v_segno = -1 then
    select string_agg(o.nome, ', ') into v_mancanti
    from jsonb_array_elements(m.voci) e
    join oggetti o on o.id = (e->>'oggetto_id')::uuid
    where coalesce(o.quantita_disponibile, 0) < (e->>'qty')::int;
    if v_mancanti is not null then
      raise exception 'Alcuni pezzi di questo carico sono già stati presi: %', v_mancanti;
    end if;
  end if;

  update oggetti o
     set quantita_disponibile = coalesce(o.quantita_disponibile, 0) + v_segno * (e->>'qty')::int
    from jsonb_array_elements(m.voci) e
   where o.id = (e->>'oggetto_id')::uuid;

  update movimenti_armadio set annullato_il = now() where id = p_id;

  if m.tipo = 'carico' and m.ordine_id is not null then
    update ordini_forniture set stato = 'inviato', arrivato_il = null where id = m.ordine_id;
  end if;

  return jsonb_build_object('id', p_id, 'tipo', m.tipo);
end;
$$;

-- ---------- Movimenti vecchi: ricostruisco i pezzi per le statistiche ----------
do $$
declare
  m record;
  parte text;
  v_voci jsonb;
  v_nome text;
  v_qty int;
begin
  for m in select id, dettagli from movimenti_armadio where voci is null and coalesce(dettagli, '') <> '' loop
    v_voci := '[]'::jsonb;
    foreach parte in array string_to_array(m.dettagli, ', ') loop
      if parte like 'KIT %' then
        v_voci := v_voci || coalesce((
          select jsonb_agg(jsonb_build_object('oggetto_id', o.id, 'nome', o.nome, 'qty', coalesce(c.quantita_necessaria, 1)))
          from pacchetti p
          join componenti_pacchetto c on c.pacchetto_id = p.id
          join oggetti o on o.id = c.oggetto_id
          where p.nome = substr(parte, 5)), '[]'::jsonb);
      elsif parte ~ ' x[0-9]+$' then
        v_nome := regexp_replace(parte, ' x[0-9]+$', '');
        v_qty := substring(parte from ' x([0-9]+)$')::int;
        v_voci := v_voci || coalesce((
          select jsonb_agg(jsonb_build_object('oggetto_id', o.id, 'nome', o.nome, 'qty', v_qty))
          from oggetti o where o.nome = v_nome), '[]'::jsonb);
      end if;
    end loop;
    if jsonb_array_length(v_voci) > 0 then
      update movimenti_armadio set voci = v_voci where id = m.id;
    end if;
  end loop;
end $$;

